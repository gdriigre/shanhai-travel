const provinceSearchForm = document.getElementById("provinceSearchForm");
if (provinceSearchForm) {
  const input = document.getElementById("provinceSearchInput");
  const status = document.getElementById("provinceSearchStatus");
  const results = document.getElementById("provinceSearchResults");
  const normalize = (value) => value.normalize("NFKC").trim().toLowerCase().replace(/[\s\-_’']/g, "").replace(/(维吾尔自治区|壮族自治区|回族自治区|特别行政区|自治区|省|市)$/, "");
  const find = () => {
    const term = normalize(input.value);
    if (!term) return [];
    return provinceData.filter((province) => normalize(province.name).includes(term) || normalize(province.slug).includes(term));
  };
  const showMatches = (matches) => {
    results.replaceChildren();
    results.hidden = matches.length === 0;
    matches.forEach((province) => {
      const item = document.createElement("li");
      const button = document.createElement("button");
      button.type = "button";
      button.textContent = `${province.name} ↗`;
      button.setAttribute("aria-label", `进入${province.name}旅游页面`);
      button.addEventListener("click", () => openProvince(province.slug));
      item.appendChild(button);
      results.appendChild(item);
    });
  };
  const update = () => {
    const term = normalize(input.value);
    if (!term) {
      showMatches([]);
      status.textContent = input.value.trim() ? "请输入有效的省份名称。" : "输入省份名称，按搜索或回车。";
      return [];
    }
    const matches = find();
    showMatches(matches);
    status.textContent = matches.length ? `找到 ${matches.length} 个地方，可点击选择。` : "没有找到这个地方，请试试其他省份名称。";
    return matches;
  };
  input.addEventListener("input", (event) => { if (!event.isComposing) update(); });
  input.addEventListener("compositionend", update);
  input.addEventListener("keydown", (event) => {
    if (event.key === "ArrowDown" && !results.hidden) { event.preventDefault(); results.querySelector("button")?.focus(); }
    else if (event.key === "Escape" && !results.hidden) { showMatches([]); status.textContent = "输入省份名称，按搜索或回车。"; }
  });
  provinceSearchForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const matches = update();
    const term = normalize(input.value);
    const exact = matches.find((province) => normalize(province.name) === term || normalize(province.slug) === term);
    if (exact || matches.length === 1) openProvince((exact || matches[0]).slug);
    else if (matches.length > 1) status.textContent = `找到 ${matches.length} 个地方，请选择你想去的省份。`;
  });
}

