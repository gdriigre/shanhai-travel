function renderProvincePage(province) {
  pageShell.hidden = true;
  provinceView.hidden = false;
  document.body.classList.add("province-mode");
  provinceView.classList.remove("sichuan-view", "featured-province-view");
  if (province.slug === "sichuan") {
    renderSichuanPage();
    window.scrollTo({ top: 0, behavior: "instant" });
    return;
  }
  if (featuredProvincePages[province.slug]) {
    renderFeaturedProvincePage(province, featuredProvincePages[province.slug]);
    window.scrollTo({ top: 0, behavior: "instant" });
    return;
  }
  renderFeaturedProvincePage(province, makeDirectoryPage(province));
  window.scrollTo({ top: 0, behavior: "instant" });
  return;

}

