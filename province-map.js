if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const discoveryObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-revealed");
      observer.unobserve(entry.target);
    });
  }, { threshold: .08 });
  document.querySelectorAll("[data-discovery-reveal]").forEach((element) => {
    element.classList.add("discovery-will-reveal");
    discoveryObserver.observe(element);
  });
}

