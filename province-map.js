function setMapZoom(enlarged, keepCenter = false) {
  if (!mapFrame || !mapCanvas || !zoomButton) return;
  const centerX = (mapFrame.scrollLeft + mapFrame.clientWidth / 2) / Math.max(mapFrame.scrollWidth, 1);
  const centerY = (mapFrame.scrollTop + mapFrame.clientHeight / 2) / Math.max(mapFrame.scrollHeight, 1);
  mapFrame.classList.toggle("is-zoomed", enlarged);
  zoomButton.setAttribute("aria-pressed", String(enlarged));
  zoomButton.textContent = enlarged ? "－ 还原地图" : "＋ 放大地图";
  if (mapGuide) mapGuide.textContent = enlarged ? "地图已放大：拖动或滑动浏览，再点省份进入。" : "点击地图或下方的地区名称；看不清时可以先放大。";
  if (keepCenter && enlarged) {
    mapFrame.scrollLeft = centerX * mapFrame.scrollWidth - mapFrame.clientWidth / 2;
    mapFrame.scrollTop = centerY * mapFrame.scrollHeight - mapFrame.clientHeight / 2;
  }
}

