function galleryDatabase() {
  if (galleryDatabasePromise) return galleryDatabasePromise;
  galleryDatabasePromise = new Promise((resolve, reject) => {
    if (!window.indexedDB) { reject(new Error("浏览器不支持照片存储")); return; }
    const request = window.indexedDB.open("shanhai-travel-photos", 1);
    request.onupgradeneeded = () => {
      const store = request.result.createObjectStore("photos", { keyPath: "id", autoIncrement: true });
      store.createIndex("province", "province", { unique: false });
    };
    request.onerror = () => reject(request.error || new Error("无法打开照片存储"));
    request.onblocked = () => reject(new Error("照片存储正在被其他页面占用"));
    request.onsuccess = () => {
      const db = request.result;
      db.onversionchange = () => { db.close(); galleryDatabasePromise = null; };
      resolve(db);
    };
  }).catch((error) => { galleryDatabasePromise = null; throw error; });
  return galleryDatabasePromise;
}

