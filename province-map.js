function svgNode(name, attributes = {}) {
  const node = document.createElementNS("http://www.w3.org/2000/svg", name);
  Object.entries(attributes).forEach(([key, value]) => node.setAttribute(key, value));
  return node;
}

function setProvinceHover(slug, isActive, event) {
  mapOverlay?.querySelectorAll(`[data-slug="${slug}"]`).forEach((path) => path.classList.toggle("is-hovered", isActive));
  if (!mapTooltip || !mapCanvas) return;
  if (!isActive) {
    mapTooltip.hidden = true;
    return;
  }
  const province = provinceBySlug.get(slug);
  const rect = mapCanvas.getBoundingClientRect();
  const x = event?.clientX ? event.clientX - rect.left : ((province.center[0] - 225) / 1010) * rect.width;
  const y = event?.clientY ? event.clientY - rect.top : ((province.center[1] - 75) / 865) * rect.height;
  mapTooltip.textContent = `${province.name} · 点击进入`;
  mapTooltip.style.left = `${Math.max(8, Math.min(rect.width - 125, x))}px`;
  mapTooltip.style.top = `${Math.max(24, Math.min(rect.height - 12, y))}px`;
  mapTooltip.hidden = false;
}

function openProvince(slug) {
  if (!provinceBySlug.has(slug)) return;
  rememberMapView(slug);
  const navigate = () => {
    window.history.pushState({ province: slug }, "", `/shanhai-travel/province/${slug}`);
    renderRoute();
  };
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if ((slug === "hunan" || slug === "yunnan") && !reduceMotion && typeof document.startViewTransition === "function") {
    const transitionClass = `${slug}-transition`;
    document.documentElement.classList.add(transitionClass);
    try {
      const transition = document.startViewTransition(navigate);
      const clearTransition = () => document.documentElement.classList.remove(transitionClass);
      transition.finished.then(clearTransition, clearTransition);
    } catch {
      document.documentElement.classList.remove(transitionClass);
      navigate();
    }
  } else navigate();
}

let openingProvince = null;
function activateProvince(slug) {
  if (openingProvince || !provinceBySlug.has(slug)) return;
  mapOverlay?.querySelectorAll(`[data-slug="${slug}"]`).forEach((path) => path.classList.add("is-pressed"));
  if (mapTooltip) mapTooltip.hidden = true;
  const delay = window.matchMedia("(prefers-reduced-motion: reduce)").matches ? 0 : 230;
  openingProvince = window.setTimeout(() => {
    openingProvince = null;
    openProvince(slug);
  }, delay);
}

function addProvincePath(province, d, pathIndex) {
  const path = svgNode("path", {
    d,
    "fill-rule": "evenodd",
    class: `province-hit${isMapDebug ? " is-debug" : ""}`,
    tabindex: "0",
    role: "button",
    "aria-label": `进入${province.name}旅游页面`,
    "data-slug": province.slug,
    "data-path-index": pathIndex,
  });
  path.addEventListener("pointerenter", (event) => setProvinceHover(province.slug, true, event));
  path.addEventListener("pointermove", (event) => setProvinceHover(province.slug, true, event));
  path.addEventListener("pointerleave", () => setProvinceHover(province.slug, false));
  path.addEventListener("focus", () => setProvinceHover(province.slug, true));
  path.addEventListener("blur", () => setProvinceHover(province.slug, false));
  path.addEventListener("click", (event) => {
    event.preventDefault();
    activateProvince(province.slug);
  });
  path.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      activateProvince(province.slug);
    }
  });
  mapOverlay.appendChild(path);
}

